Flag = Literal["ai_welcome", "ai_discouraged", "ai_prohibited", "must_disclose", "human_testing_required",
               "own_words_only", "no_autonomous_agents", "newcomer_issues_reserved"]


class Rule(BaseModel):
    flag: Flag
    quote: str


class FlagAnswer(BaseModel):
    applies: bool
    quote: str = Field(default="", max_length=400,
                       description="the sentence that says it, copied word for word; empty when it does not apply")


class Policy(BaseModel):
    stance: Literal["welcome", "conditions", "discouraged", "prohibited", "unspecified"] = "unspecified"
    must_disclose: bool = False
    human_testing_required: bool = False
    own_words_only: bool = False
    no_autonomous_agents: bool = False
    newcomer_issues_reserved: bool = False
    dco: bool = False
    cla: bool = False
    rules: list[Rule] = Field(default_factory=list)
    dropped: int = 0
    rejected: int = 0


PROMPT_VERSION = 4
QUESTIONS: dict[str, str] = {
    "ai_welcome": "Does the project explicitly allow or welcome contributors using AI tools for code?",
    "ai_discouraged": "Does the project say that using AI tools is discouraged in general (not banned, and not "
                      "just a rule about one particular use)?",
    "ai_prohibited": "Does the project refuse all AI-assisted or AI-generated contributions?",
    "must_disclose": "Must or should contributors state whether and how they used AI tools?",
    "human_testing_required": "Must the contributor run or test the change personally, or attach proof such as "
                              "screenshots or video?",
    "own_words_only": "Must pull request descriptions, comments or replies to maintainers be written by the "
                      "contributor rather than generated by AI?",
    "no_autonomous_agents": "Does the project forbid AI agents or bots from opening pull requests, issues or "
                            "comments on their own or on someone's behalf?",
    "newcomer_issues_reserved": "Does the project say beginner issues are meant for new human contributors?",
}

class Check(BaseModel):
    says_it: bool


# These decide whether a project is skipped, so a wrong yes costs a lot: they get a second check. The caution
# rules (disclose, test yourself, own words, no agents) keep every grounded yes, because missing one is the
# expensive mistake and an extra one is a checklist item with its quote next to it.
STANCE_FLAGS = {"ai_welcome", "ai_discouraged", "ai_prohibited"}


VERIFY_PROMPT = """You check one sentence from a project's contribution guidelines. Answer only whether the sentence,
on its own, states what the question asks. A sentence that only mentions AI, or states a different rule, does not.
Reply with JSON only: {"says_it": true|false}."""

POLICY_PROMPT = """You answer one yes/no question about a project's rules for AI-assisted contributions, using only
the text given. Reply with JSON only: {"applies": true|false, "quote": "..."}.
If it applies, copy the one sentence that says it, word for word. If the text does not say it, answer false with an
empty quote. Statements about maintainers' own use of AI, or about AI-generated images, do not count."""


def assess_policy(facts: RepoFacts) -> Policy:
    """One question per rule; a rule only counts when its quote is really in the project's files."""
    if not facts.ai_excerpts:
        return Policy(dco=facts.dco, cla=facts.cla)
    key = hashlib.sha256(json.dumps([llm.MODEL, PROMPT_VERSION, facts.ai_excerpts]).encode()).hexdigest()
    cached = CACHE / "policies" / f"{key}.json"
    if cached.exists():
        return Policy.model_validate_json(cached.read_text())
    policy = _assess_policy(facts)
    cached.parent.mkdir(parents=True, exist_ok=True)
    cached.write_text(policy.model_dump_json())
    return policy


def _assess_policy(facts: RepoFacts) -> Policy:
    policy = Policy(dco=facts.dco, cla=facts.cla)
    text = "\n\n".join(facts.ai_excerpts)
    sources = list(facts.policy_text.values())
    flags = set()
    for flag, question in QUESTIONS.items():
        answer, _ = llm.structured(POLICY_PROMPT, f"Question: {question}\n\nRepository: {facts.repo}\n\n{text}",
                                   FlagAnswer)
        if not answer.applies:
            continue
        if not llm.grounded(answer.quote, *sources):
            policy.dropped += 1
            continue
        if flag in STANCE_FLAGS:
            check, _ = llm.structured(VERIFY_PROMPT, f"Question: {question}\n\nSentence: {answer.quote}", Check)
        else:
            check = Check(says_it=True)
        if check.says_it:
            flags.add(flag)
            policy.rules.append(Rule(flag=flag, quote=answer.quote))
        else:
            policy.rejected += 1
    policy.must_disclose = "must_disclose" in flags
    policy.human_testing_required = "human_testing_required" in flags
    policy.own_words_only = "own_words_only" in flags
    policy.no_autonomous_agents = "no_autonomous_agents" in flags
    policy.newcomer_issues_reserved = "newcomer_issues_reserved" in flags
    if "ai_prohibited" in flags and "ai_welcome" not in flags:
        policy.stance = "prohibited"
    elif "ai_discouraged" in flags:
        policy.stance = "discouraged"
    elif flags & {"must_disclose", "human_testing_required", "own_words_only", "no_autonomous_agents"}:
        policy.stance = "conditions"
    elif "ai_welcome" in flags:
        policy.stance = "welcome"
    return policy


class Claim(BaseModel):
    author: str = Field(max_length=60)
    quote: str = Field(max_length=300, description="exact words from that comment")


class IssueDraft(BaseModel):
    summary: str = Field(max_length=400, description="one or two sentences: what the issue asks for")
    must_do: list[str] = Field(default_factory=list, max_length=6,
                               description="every concrete thing a complete fix has to do, including parts the "
                                           "issue calls optional; one short line each")
    claims: list[Claim] = Field(default_factory=list, max_length=6,
                                description="people who said they are working on it or asked to take it")
    clarity: Literal["clear", "needs_discussion", "vague"] = "clear"
    effort: Literal["S", "M", "L"] = "M"
    fit_reason: str = Field(default="", max_length=300)
    fit: Literal["strong", "ok", "weak"] = "ok"
    maintainer_go_ahead: bool = Field(default=False,
                                      description="a maintainer agreed with the approach or asked for a PR")
    open_questions: list[str] = Field(default_factory=list, max_length=4,
                                      description="decisions still open in the thread")


class IssueVerdict(BaseModel):
    status: Literal["free", "claimed", "stale_claim", "in_progress"]
    status_reason: str
    draft: IssueDraft
    dropped_claims: int = 0


ISSUE_PROMPT = """You help one open source contributor decide whether an issue is worth their time.
Reply with JSON only, following the schema. Be concrete and short: one line per list item.
- "claims": everyone in the comments who said they are working on the issue, asked to be assigned, or said
  they will open a pull request. Copy their words exactly in "quote". Maintainers explaining the issue are not claims.
- "must_do": the full scope. If the thread adds requirements or safeguards, include them.
- "fit": compare the issue with the contributor profile."""


def assess_issue(candidate: Candidate, profile: Profile, now: datetime | None = None) -> IssueVerdict:
    now = now or datetime.now(timezone.utc)
    me = {"languages": profile.languages, "domains": profile.domains, "skills": profile.skills,
          "has_merged_here_before": candidate.welcomed_before}
    user = json.dumps({"contributor": me, "issue": issue_digest(candidate)}, ensure_ascii=False)
    draft, _ = llm.structured(ISSUE_PROMPT, user, IssueDraft)

    by_author: dict[str, list[dict]] = {}
    for c in candidate.comments:
        by_author.setdefault(c["author"], []).append(c)
    real, dropped = [], 0
    for claim in draft.claims:
        author = claim.author.lstrip("@")
        matches = [c for c in by_author.get(author, []) if llm.grounded(claim.quote, c["body"])]
        if matches and author != profile.github:
            real.append((author, matches[-1]["created_at"]))
        else:
            dropped += 1

    if candidate.open_prs:
        status, reason = "in_progress", f"open pull request: {candidate.open_prs[0]}"
    elif real:
        author, when = max(real, key=lambda r: r[1])
        age = (now - datetime.fromisoformat(when.replace("Z", "+00:00"))).days
        status = "claimed" if age <= 45 else "stale_claim"
        reason = f"@{author} said they would take it {age} days ago"
    else:
        status, reason = "free", "nobody has claimed it and no pull request is linked"
    return IssueVerdict(status=status, status_reason=reason, draft=draft, dropped_claims=dropped)
